def evaluate_actor_context(threat_actor_name, generated_context):
    """
    Evaluate the quality of LLM-generated context about a threat actor.

    Parameters:
    - threat_actor_name: str, the name of the threat actor for reference.
    - generated_context: str, the context generated by the LLM about the threat actor.

    Returns:
    - evaluation_scores: dict, containing scores for each evaluation criterion.
    """
    sys_prompt = """
    ### Task description:
    You are an expert evaluator in cybersecurity. I will provide you with the name of a threat actor and the corresponding LLM-generated context.
    Your task is to assess the quality of the LLM-generated context based on the following criteria and scoring metrics:

    ### Evaluation Criteria and Metrics:

    1. Relevance:
        - 1: Unrelated to the threat actor or fails to mention key aspects (e.g., aliases, motivations, tactics).
        - 2: Limited relevance; partial or tangentially related information but misses key aspects.
        - 3: Moderately relevant; covers some important aspects but lacks depth or misses critical details.
        - 4: Mostly relevant; covers most key aspects with minor omissions or inaccuracies.
        - 5: Highly relevant; fully aligns with the threat actor, addressing all key aspects comprehensively.

    2. Accuracy:
        - 1: Factually incorrect or inconsistent with known information about the threat actor.
        - 2: Significant inaccuracies or contradictions, though some elements are correct.
        - 3: Moderately accurate; factual but contains minor inconsistencies or errors.
        - 4: Mostly accurate; aligns well with known information about the threat actor with very few errors.
        - 5: Completely accurate; perfectly reflects known factual content about the threat actor.

    3. Comprehensiveness:
        - 1: Highly incomplete; fails to cover critical details about the threat actor.
        - 2: Covers only minimal details; significant gaps remain in the explanation.
        - 3: Moderately comprehensive; includes some critical details but misses others.
        - 4: Comprehensive; covers most critical details with minor omissions.
        - 5: Fully comprehensive; captures all essential details (e.g., aliases, campaigns, tactics).

    4. Clarity:
        - 1: Poorly written, unclear, and difficult to understand.
        - 2: Significant clarity issues; partially understandable but requires effort to interpret.
        - 3: Moderately clear; generally understandable but with some ambiguities.
        - 4: Mostly clear; easy to understand with minor issues.
        - 5: Perfectly clear; highly readable and easily understandable.

    5. Coherence:
        - 1: Disorganized, lacks logical structure, and is difficult to follow.
        - 2: Significant coherence issues; information is scattered or poorly organized.
        - 3: Moderately coherent; some structure exists, but logical flow is inconsistent.
        - 4: Mostly coherent; well-organized with minor issues in logical flow.
        - 5: Fully coherent; logically structured, well-organized, and easy to follow.

    6. Attribution:
        - 1: Information cannot be verified or attributed to known sources about the threat actor.
        - 2: Attribution issues; some details are unverifiable or not clearly linked.
        - 3: Moderately attributable; most information is verifiable, but some details lack attribution.
        - 4: Mostly attributable; the majority of content is clearly linked, with minor gaps.
        - 5: Fully attributable; all information is verifiable and clearly linked.

    ### Evaluation Instructions:
    For each criterion, assign a score between 1 and 5 based on the metrics provided above. Then output the evaluation scores strictly in the JSON format below without any prefixes or explanations:
    {"Relevance": <score>, "Accuracy": <score>, "Comprehensiveness": <score>, "Clarity": <score>, "Coherence": <score>, "Attribution": <score>}

    Do not include any additional text or comments outside the JSON object.
    """

    user_prompt = f"""
    ### Task description:
    Evaluate the generated context for the given threat actor based on the provided criteria and metrics.

    Threat Actor Name:
    {threat_actor_name}

    Generated Context:
    {generated_context}
    """

    # Prepare messages for API call
    new_messages = [{"role": "system", "content": sys_prompt}]
    new_messages.append({"role": "user", "content": user_prompt})

    # Call the API to perform the evaluation
    response_message = api_call(new_messages, temperature=0.01, model="gpt-4o", json_enabled=True)
    response = response_message.choices[0].message.content
    # print(response)

    # Parse the JSON response
    try:
        evaluation_scores = json.loads(response)
    except json.JSONDecodeError as e:
        print(f"Error parsing evaluation response: {e}")
        evaluation_scores = {"error": "Unable to parse scores"}

    return evaluation_scores


